import type { ApiIssue } from "@/data/api/errors";
import type { Badge, NewBadge } from "@/data/schemas/badge";
import type { ContentStatus } from "@/data/schemas/common";
import { plural } from "./text";

// What makes a badge acceptable, and where a badge is in use. One set of
// rules, used by the form, by the actions and by the mock server.

export const BADGE_NAME_MIN = 3;
/** Badge pictures live in one folder of the media library. */
export const BADGE_IMAGE_PREFIX = "badges/";

export const BADGE_TYPES = [
	"normal",
	"manual",
	"milestone",
	"perfections",
] as const;
/** The other two are generated by the backend. */
export const CREATABLE_BADGE_TYPES = ["normal", "manual"] as const;
export const SPECIAL_CATEGORIES = ["event", "specialTraining"] as const;

const CLAIM_TOKEN = /^[A-Za-z0-9]{6,32}$/;

/** A workout or challenge that awards a badge. */
export interface BadgeAssignment {
	kind: "workout" | "challenge";
	id: string;
	title: string;
	/** "perfect": awarded for completing every day of a challenge. */
	role: "completion" | "perfect";
	/** In the trash, from where it can still be restored. */
	deleted: boolean;
}

interface AwardingWorkout {
	id: string;
	title: string;
	status: ContentStatus;
	badgeId: string | null;
}

interface AwardingChallenge extends AwardingWorkout {
	perfectCompletionBadgeId: string | null;
}

/** Every assignment, by badge id. Derived: nothing stores this list. */
export function assignmentsByBadge(
	workouts: readonly AwardingWorkout[],
	challenges: readonly AwardingChallenge[],
): Map<string, BadgeAssignment[]> {
	const byBadge = new Map<string, BadgeAssignment[]>();
	const add = (badgeId: string | null, assignment: BadgeAssignment) => {
		if (!badgeId) return;
		const list = byBadge.get(badgeId) ?? [];
		list.push(assignment);
		byBadge.set(badgeId, list);
	};
	for (const challenge of challenges) {
		const base = {
			kind: "challenge" as const,
			id: challenge.id,
			title: challenge.title,
			deleted: challenge.status === "deleted",
		};
		add(challenge.badgeId, { ...base, role: "completion" });
		add(challenge.perfectCompletionBadgeId, { ...base, role: "perfect" });
	}
	for (const workout of workouts) {
		add(workout.badgeId, {
			kind: "workout",
			id: workout.id,
			title: workout.title,
			role: "completion",
			deleted: workout.status === "deleted",
		});
	}
	return byBadge;
}

export function describeAssignment(assignment: BadgeAssignment): string {
	const what = assignment.kind === "workout" ? "Trening" : "Wyzwanie";
	const title = assignment.title || "bez nazwy";
	const role = assignment.role === "perfect" ? ", za wykonanie w 100%" : "";
	const trash = assignment.deleted ? " (w koszu)" : "";
	return `${what} „${title}”${role}${trash}`;
}

/** A short list for a message: the first few, then how many more. */
export function describeAssignments(
	assignments: readonly BadgeAssignment[],
	max = 3,
): string {
	const shown = assignments.slice(0, max).map(describeAssignment).join("; ");
	const rest = assignments.length - max;
	return rest > 0 ? `${shown} i jeszcze ${rest}` : shown;
}

/** A badge people claim with a code, a link or a QR. */
export const isEventBadge = (
	badge: Pick<NewBadge, "type" | "specialCategory">,
): boolean => badge.type === "manual" && badge.specialCategory === "event";

/** The address the app opens to claim an event badge. */
export const claimLink = (claimToken: string): string =>
	`codzienniefit://badge?code=${encodeURIComponent(claimToken)}`;

export interface BadgeContext {
	/** Where this badge is assigned now. */
	assignments: readonly BadgeAssignment[];
	/** Claim codes other badges use, in lower case. */
	takenClaimTokens?: ReadonlySet<string>;
	/** The stored type when editing; absent when creating. */
	storedType?: string;
}

export function badgeIssues(
	badge: NewBadge,
	context: BadgeContext,
): ApiIssue[] {
	const issues: ApiIssue[] = [];
	const add = (path: string, message: string) => issues.push({ path, message });
	const title = badge.name.trim();
	const known = (BADGE_TYPES as readonly string[]).includes(badge.type);
	const manual = badge.type === "manual";

	if (!title) {
		add("name", "Nazwa jest wymagana");
	} else if (title.length < BADGE_NAME_MIN) {
		add("name", `Nazwa musi mieć co najmniej ${BADGE_NAME_MIN} znaki`);
	}

	if (!badge.imageRelativePath) {
		add("imageRelativePath", "Wybierz grafikę odznaki");
	} else if (!badge.imageRelativePath.startsWith(BADGE_IMAGE_PREFIX)) {
		add("imageRelativePath", "Grafika musi pochodzić z folderu „Odznaki”");
	}

	if (!known) {
		add("type", "Nieznany typ odznaki");
	} else if (context.storedType === undefined) {
		if (!(CREATABLE_BADGE_TYPES as readonly string[]).includes(badge.type)) {
			add(
				"type",
				"Odznaki tego typu tworzy system. Ręcznie można dodać tylko odznakę za trening lub wyzwanie albo odznakę ręczną",
			);
		}
	} else if (context.storedType !== badge.type) {
		add("type", "Typu istniejącej odznaki nie można zmienić");
	}

	if (manual) {
		if (!badge.specialCategory) {
			add("specialCategory", "Wybierz rodzaj odznaki ręcznej");
		} else if (
			!(SPECIAL_CATEGORIES as readonly string[]).includes(badge.specialCategory)
		) {
			add("specialCategory", "Nieznany rodzaj odznaki ręcznej");
		}
		if (badge.activeFromUtc || badge.activeTillUtc) {
			add("activeFromUtc", "Odznaka ręczna nie ma dat widoczności");
		}
	} else if (badge.specialCategory) {
		add("specialCategory", "Rodzaj mają tylko odznaki ręczne");
	}

	if (
		badge.activeFromUtc &&
		badge.activeTillUtc &&
		badge.activeTillUtc <= badge.activeFromUtc
	) {
		add("activeTillUtc", "„Widoczna do” musi być później niż „Widoczna od”");
	}

	if (isEventBadge(badge)) {
		const token = badge.claimToken ?? "";
		if (token && !CLAIM_TOKEN.test(token)) {
			add(
				"claimToken",
				"Kod musi mieć od 6 do 32 znaków: same litery (bez polskich) i cyfry",
			);
		} else if (token && context.takenClaimTokens?.has(token.toLowerCase())) {
			add("claimToken", "Tego kodu używa już inna odznaka");
		}
	} else if (badge.claimToken || badge.isClaimLinkActive) {
		add(
			"claimToken",
			"Kod do zdobycia mają tylko odznaki ręczne za wydarzenie",
		);
	}

	if (badge.isHidden && context.assignments.length > 0) {
		add(
			"isHidden",
			`Nie można ukryć odznaki, która jest przypisana: ${describeAssignments(context.assignments)}. Najpierw wybierz tam inną odznakę`,
		);
	}
	return issues;
}

/** Why a badge cannot be deleted; empty when it can. */
export function badgeRemovalIssues(
	assignments: readonly BadgeAssignment[],
): ApiIssue[] {
	if (assignments.length === 0) return [];
	return [
		{
			path: "id",
			message: `Nie można usunąć odznaki, która jest przypisana: ${describeAssignments(assignments)}. Najpierw wybierz tam inną odznakę`,
		},
	];
}

/** One line about how a badge is earned, for the list. */
export function badgeSummary(
	badge: Pick<
		Badge,
		| "type"
		| "milestoneCount"
		| "specialCategory"
		| "claimToken"
		| "isClaimLinkActive"
	>,
	assignments: readonly BadgeAssignment[],
): string {
	if (badge.type === "milestone") {
		return badge.milestoneCount
			? `Za ${plural(badge.milestoneCount, "powtórzenie", "powtórzenia", "powtórzeń")}`
			: "Za powtórzenia";
	}
	if (badge.type === "perfections") return "Za wykonania w 100%";
	if (badge.type === "manual") {
		if (!isEventBadge(badge)) return "Przyznawana ręcznie";
		return badge.isClaimLinkActive && badge.claimToken
			? "Do zdobycia kodem: aktywna"
			: "Do zdobycia kodem: wyłączona";
	}
	if (assignments.length === 0) return "Nieprzypisana";
	// A challenge can award the same badge twice (for finishing and for 100%).
	const count = (kind: BadgeAssignment["kind"]) =>
		new Set(assignments.filter((a) => a.kind === kind).map((a) => a.id)).size;
	const workouts = count("workout");
	const challenges = count("challenge");
	const parts = [
		workouts && plural(workouts, "trening", "treningi", "treningów"),
		challenges && plural(challenges, "wyzwanie", "wyzwania", "wyzwań"),
	].filter(Boolean);
	return `Przypisana: ${parts.join(" i ")}`;
}
